use auditstream_pg::ddl::DEFAULT_SCHEMA;
use auditstream_pg::introspect::{
    self, GeneratedKind, IdentityKind, IntrospectError, IntrospectOptions, PartitionInfo,
    TableInfo, TableKind,
};
use auditstream_testkit::TestDb;
use sqlx::Executor;
use sqlx::postgres::PgPoolOptions;

fn normalize_oids(mut tables: Vec<TableInfo>) -> Vec<TableInfo> {
    fn clear_partition_oids(parts: &mut [PartitionInfo]) {
        for p in parts {
            assert!(p.oid > 0, "partition `{}` must report a real OID", p.name);
            p.oid = 0;
            clear_partition_oids(&mut p.partitions);
        }
    }

    for t in &mut tables {
        assert!(t.oid > 0, "table `{}` must report a real OID", t.name);
        t.oid = 0;
        clear_partition_oids(&mut t.partitions);
    }
    tables
}

#[tokio::test]
#[allow(clippy::too_many_lines)]
async fn introspect_fixture_schema_matches_snapshot_and_skips_non_capturable_relations() {
    let db = TestDb::new().await.expect("create TestDb");
    let pool = PgPoolOptions::new()
        .max_connections(2)
        .connect(db.url())
        .await
        .expect("connect test db");

    // Create the auditstream schema and a table inside it without creating cluster-wide roles,
    // confirming introspection skips the audit schema even when passed explicitly.
    pool.execute("CREATE SCHEMA auditstream")
        .await
        .expect("create auditstream schema");
    pool.execute("CREATE TABLE auditstream.changes (id bigint PRIMARY KEY)")
        .await
        .expect("create auditstream.changes");

    // Create fixture schema with every edge case from the specification.
    pool.execute("CREATE SCHEMA fixture")
        .await
        .expect("create schema fixture");

    // 1. Ordinary table with identity (always + by default? PG allows 1 identity per table, so two tables),
    //    stored generated column, nullable/not-null columns, and a dropped column.
    pool.execute(
        "CREATE TABLE fixture.invoice ( \
           id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, \
           status text NOT NULL, \
           subtotal numeric(12,2) NOT NULL, \
           tax numeric(12,2) NOT NULL, \
           total numeric(12,2) GENERATED ALWAYS AS (subtotal + tax) STORED, \
           obsolete text, \
           notes text \
         )",
    )
    .await
    .expect("create invoice");
    pool.execute("ALTER TABLE fixture.invoice DROP COLUMN obsolete")
        .await
        .expect("drop obsolete column");

    // 2. Mixed-case table & column names + GENERATED BY DEFAULT AS IDENTITY.
    pool.execute(
        r#"CREATE TABLE fixture."MixedCase" (
             "UserId" int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
             "DisplayName" varchar(120)
           )"#,
    )
    .await
    .expect("create MixedCase");

    // 3. Name with a space + composite primary key declared in reverse attnum order.
    pool.execute(
        r#"CREATE TABLE fixture."Order Items" (
             seq_no int NOT NULL,
             tenant_id uuid NOT NULL,
             "Unit Price" numeric(10,2) NOT NULL,
             PRIMARY KEY (tenant_id, seq_no)
           )"#,
    )
    .await
    .expect("create Order Items");

    // 4. Table with NO primary key (still capturable with empty primary_key).
    pool.execute("CREATE TABLE fixture.event_notes (body text NOT NULL, created_at timestamptz)")
        .await
        .expect("create event_notes");

    // 5. Partitioned table with sub-partitions + DEFAULT partition (none appear top-level).
    pool.execute(
        "CREATE TABLE fixture.ledger ( \
           region text NOT NULL, \
           ym int NOT NULL, \
           amount numeric NOT NULL, \
           PRIMARY KEY (region, ym) \
         ) PARTITION BY LIST (region)",
    )
    .await
    .expect("create ledger");
    pool.execute(
        "CREATE TABLE fixture.ledger_us PARTITION OF fixture.ledger \
         FOR VALUES IN ('us') PARTITION BY RANGE (ym)",
    )
    .await
    .expect("create ledger_us");
    pool.execute(
        "CREATE TABLE fixture.ledger_us_2026 PARTITION OF fixture.ledger_us \
         FOR VALUES FROM (202601) TO (202701)",
    )
    .await
    .expect("create ledger_us_2026");
    pool.execute(
        "CREATE TABLE fixture.ledger_eu PARTITION OF fixture.ledger \
         FOR VALUES IN ('eu')",
    )
    .await
    .expect("create ledger_eu");
    pool.execute("CREATE TABLE fixture.ledger_default PARTITION OF fixture.ledger DEFAULT")
        .await
        .expect("create ledger_default");

    // 6. Relations that MUST be skipped:
    //    - view
    pool.execute("CREATE VIEW fixture.invoice_view AS SELECT id, status FROM fixture.invoice")
        .await
        .expect("create view");
    //    - materialized view
    pool.execute(
        "CREATE MATERIALIZED VIEW fixture.invoice_matview AS SELECT id FROM fixture.invoice",
    )
    .await
    .expect("create matview");
    //    - foreign table (built-in FDW DDL, no external extension required)
    pool.execute("CREATE FOREIGN DATA WRAPPER fixture_fdw")
        .await
        .expect("create fdw");
    pool.execute("CREATE SERVER fixture_srv FOREIGN DATA WRAPPER fixture_fdw")
        .await
        .expect("create foreign server");
    pool.execute("CREATE FOREIGN TABLE fixture.remote_invoices (id int) SERVER fixture_srv")
        .await
        .expect("create foreign table");
    //    - migration tool tables
    pool.execute("CREATE TABLE fixture._prisma_migrations (id text PRIMARY KEY)")
        .await
        .expect("create _prisma_migrations");
    pool.execute("CREATE TABLE fixture.__drizzle_migrations (id serial PRIMARY KEY)")
        .await
        .expect("create __drizzle_migrations");
    //    - extension member table (identical pg_depend deptype='e' semantics as PostGIS spatial_ref_sys)
    pool.execute("CREATE TABLE fixture.spatial_ref_sys (srid int PRIMARY KEY)")
        .await
        .expect("create spatial_ref_sys");
    pool.execute("ALTER EXTENSION plpgsql ADD TABLE fixture.spatial_ref_sys")
        .await
        .expect("attach spatial_ref_sys to extension");

    //    - temporary table on a pinned session connection (must also be skipped)
    let mut conn = pool.acquire().await.expect("acquire conn");
    conn.execute("CREATE TEMP TABLE scratch_temp (id int PRIMARY KEY)")
        .await
        .expect("create temp table");
    drop(conn);

    // Introspect fixture + auditstream + pg_catalog + information_schema together.
    let tables = introspect::tables(
        &pool,
        &[
            "fixture",
            DEFAULT_SCHEMA,
            "pg_catalog",
            "information_schema",
        ],
    )
    .await
    .expect("introspect fixture");

    // Explicit sanity checks before snapshot.
    assert_eq!(tables.len(), 5);
    assert_eq!(tables[0].name, "MixedCase");
    assert_eq!(tables[0].columns[0].identity, Some(IdentityKind::ByDefault));
    assert_eq!(tables[1].name, "Order Items");
    assert_eq!(tables[1].primary_key, vec!["tenant_id", "seq_no"]);
    assert_eq!(tables[2].name, "event_notes");
    assert_eq!(tables[2].primary_key, Vec::<String>::new());
    assert_eq!(tables[3].name, "invoice");
    assert_eq!(tables[3].columns[0].identity, Some(IdentityKind::Always));
    assert_eq!(tables[3].columns[4].generated, Some(GeneratedKind::Stored));
    assert!(tables[3].columns.iter().all(|c| c.name != "obsolete"));
    assert_eq!(tables[4].name, "ledger");
    assert_eq!(tables[4].kind, TableKind::Partitioned);
    assert_eq!(tables[4].partitions.len(), 3);

    // Custom audit schema option skips that custom schema too.
    let skipped_custom = introspect::tables_with_options(
        &pool,
        &["fixture"],
        &IntrospectOptions::with_audit_schema("fixture"),
    )
    .await
    .expect("custom audit schema skipped");
    assert_eq!(skipped_custom, Vec::new());

    let normalized = normalize_oids(tables);
    insta::assert_debug_snapshot!("fixture_schema", normalized);

    pool.close().await;
    drop(db);
}

#[tokio::test]
async fn unknown_schema_returns_error_and_empty_schema_returns_empty_list() {
    let db = TestDb::new().await.expect("create TestDb");
    let pool = PgPoolOptions::new()
        .max_connections(2)
        .connect(db.url())
        .await
        .expect("connect test db");

    pool.execute("CREATE SCHEMA empty_one")
        .await
        .expect("create empty_one");

    let empty = introspect::tables(&pool, &["empty_one"])
        .await
        .expect("introspect empty schema");
    assert_eq!(empty, Vec::new());

    let err = introspect::tables(&pool, &["empty_one", "missing_schema_xyz"])
        .await
        .expect_err("unknown schema must fail");
    assert!(
        matches!(err, IntrospectError::UnknownSchema { ref schema } if schema == "missing_schema_xyz"),
        "expected UnknownSchema naming missing_schema_xyz, got {err:?}"
    );
    assert!(err.to_string().contains("missing_schema_xyz"));

    pool.close().await;
    drop(db);
}

#[tokio::test]
async fn introspects_300_tables_with_fixed_query_count() {
    let db = TestDb::new().await.expect("create TestDb");
    let pool = PgPoolOptions::new()
        .max_connections(2)
        .connect(db.url())
        .await
        .expect("connect test db");

    pool.execute("CREATE SCHEMA bulk_300")
        .await
        .expect("create bulk_300");

    // Create 300 tables in a single server-side DO block so setup stays fast.
    pool.execute(
        "DO $$ \
         DECLARE i int; \
         BEGIN \
           FOR i IN 1..300 LOOP \
             EXECUTE format( \
               'CREATE TABLE bulk_300.tbl_%s (id int PRIMARY KEY, label text NOT NULL, val int)', \
               lpad(i::text, 3, '0') \
             ); \
           END LOOP; \
         END $$",
    )
    .await
    .expect("create 300 tables");

    let tables = introspect::tables(&pool, &["bulk_300"])
        .await
        .expect("introspect 300 tables");

    assert_eq!(tables.len(), 300);
    for (idx, table) in tables.iter().enumerate() {
        let expected_name = format!("tbl_{:03}", idx + 1);
        assert_eq!(table.schema, "bulk_300");
        assert_eq!(table.name, expected_name);
        assert_eq!(table.kind, TableKind::Ordinary);
        assert_eq!(table.primary_key, vec!["id"]);
        assert_eq!(table.columns.len(), 3);
        assert_eq!(table.columns[0].name, "id");
        assert_eq!(table.columns[1].name, "label");
        assert!(!table.columns[1].nullable);
        assert_eq!(table.columns[2].name, "val");
        assert!(table.columns[2].nullable);
    }

    pool.close().await;
    drop(db);
}

#[tokio::test]
async fn reports_virtual_generated_columns_on_postgres_18_and_newer() {
    let db = TestDb::new().await.expect("create TestDb");
    let pool = PgPoolOptions::new()
        .max_connections(2)
        .connect(db.url())
        .await
        .expect("connect test db");

    let version_num: i32 = sqlx::query_scalar("SELECT current_setting('server_version_num')::int")
        .fetch_one(&pool)
        .await
        .expect("fetch server_version_num");

    if version_num < 180_000 {
        pool.close().await;
        drop(db);
        return;
    }

    pool.execute("CREATE SCHEMA pg18_gen")
        .await
        .expect("create pg18_gen");
    pool.execute(
        "CREATE TABLE pg18_gen.calc ( \
           id int PRIMARY KEY, \
           a int NOT NULL, \
           b int NOT NULL, \
           sum_stored int GENERATED ALWAYS AS (a + b) STORED, \
           sum_virtual int GENERATED ALWAYS AS (a + b) VIRTUAL \
         )",
    )
    .await
    .expect("create pg18 calc table");

    let tables = introspect::tables(&pool, &["pg18_gen"])
        .await
        .expect("introspect pg18_gen");

    assert_eq!(tables.len(), 1);
    let cols = &tables[0].columns;
    assert_eq!(cols[3].name, "sum_stored");
    assert_eq!(cols[3].generated, Some(GeneratedKind::Stored));
    assert_eq!(cols[4].name, "sum_virtual");
    assert_eq!(cols[4].generated, Some(GeneratedKind::Virtual));

    pool.close().await;
    drop(db);
}

#[tokio::test]
async fn connect_and_user_schemas_exclude_system_and_configured_audit_schemas() {
    let err = auditstream_pg::connect("not-a-valid-postgres-url")
        .await
        .expect_err("invalid URL must fail");
    assert!(err.to_string().contains("failed to connect to PostgreSQL"));

    let db = TestDb::new().await.expect("create TestDb");
    let pool = auditstream_pg::connect(db.url())
        .await
        .expect("connect via auditstream_pg::connect");

    db.execute("CREATE SCHEMA alpha").await.expect("alpha");
    db.execute("CREATE SCHEMA billing").await.expect("billing");
    db.execute("CREATE SCHEMA auditstream")
        .await
        .expect("auditstream");
    db.execute("CREATE SCHEMA custom_audit")
        .await
        .expect("custom_audit");

    // Create a temp table on a pinned connection so a pg_temp_* schema exists.
    let mut conn = pool.acquire().await.expect("acquire conn");
    conn.execute("CREATE TEMP TABLE tmp_scratch (id int)")
        .await
        .expect("create temp table");
    drop(conn);

    let default_schemas = introspect::user_schemas(&pool, &IntrospectOptions::default())
        .await
        .expect("user_schemas default");
    assert_eq!(
        default_schemas,
        vec![
            "alpha".to_owned(),
            "billing".to_owned(),
            "custom_audit".to_owned(),
            "public".to_owned(),
        ]
    );

    let custom_schemas =
        introspect::user_schemas(&pool, &IntrospectOptions::with_audit_schema("custom_audit"))
            .await
            .expect("user_schemas custom");
    assert_eq!(
        custom_schemas,
        vec![
            "alpha".to_owned(),
            "auditstream".to_owned(),
            "billing".to_owned(),
            "public".to_owned(),
        ]
    );

    // Exercise TestDb convenience SQL helpers (execute_batch, execute_statements, query_*).
    db.execute_batch(
        "CREATE TABLE alpha.items (id int PRIMARY KEY, label text NOT NULL); \
         INSERT INTO alpha.items VALUES (1, 'one'), (2, 'two');",
    )
    .await
    .expect("execute_batch");
    db.execute_statements(&["INSERT INTO alpha.items VALUES (3, 'three')".to_owned()])
        .await
        .expect("execute_statements");
    assert_eq!(
        db.query_scalar_i64("SELECT count(*) FROM alpha.items")
            .await
            .expect("query_scalar_i64"),
        3
    );
    assert_eq!(
        db.query_scalar_string("SELECT label FROM alpha.items WHERE id = 2")
            .await
            .expect("query_scalar_string"),
        "two"
    );
    assert_eq!(
        db.query_strings("SELECT label FROM alpha.items ORDER BY id ASC")
            .await
            .expect("query_strings"),
        vec!["one".to_owned(), "two".to_owned(), "three".to_owned()]
    );

    pool.close().await;
    drop(db);
}
