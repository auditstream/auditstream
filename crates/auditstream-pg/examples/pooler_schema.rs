//! Prints the Auditstream history schema DDL (D2) and capture triggers (D3) for the
//! four pooler-suite fixture tables (`invoice`, `line_item`, `up_t`, `up_plain`), with
//! `invoice.password_hash` excluded.

use auditstream_pg::ddl::{DEFAULT_SCHEMA, DdlOptions};
use auditstream_pg::migrations;
use auditstream_pg::triggers::TableTriggerSpec;

fn main() {
    let tables = vec![
        TableTriggerSpec::new(
            "public",
            "invoice",
            vec!["id".to_owned()],
            vec!["password_hash".to_owned()],
        ),
        TableTriggerSpec::new("public", "line_item", vec!["id".to_owned()], Vec::new()),
        TableTriggerSpec::new("public", "up_t", vec!["id".to_owned()], Vec::new()),
        TableTriggerSpec::new("public", "up_plain", vec!["id".to_owned()], Vec::new()),
    ];
    let sql = migrations::render_install_sql(
        &DdlOptions::new(DEFAULT_SCHEMA, vec!["app_user".to_owned()]),
        &tables,
    )
    .expect("render pooler schema SQL");

    println!("\\set ON_ERROR_STOP on");
    println!("-- Generated by `cargo run -p auditstream-pg --example pooler_schema`.");
    println!();
    print!("{sql}");
}
