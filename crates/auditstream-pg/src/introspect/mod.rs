//! Live PostgreSQL schema introspection for capture configuration (`auditstream init`,
//! `status`, and `verify`).
//!
//! Reads ordinary and partitioned user tables, their columns (in `attnum` order, including
//! PostgreSQL 18 virtual generated columns), primary key columns (in key position order),
//! and recursive partition trees using a fixed number of catalog queries (never one query
//! per table).

use std::collections::{HashMap, HashSet};

use sqlx::{FromRow, PgPool};
use thiserror::Error;

use crate::ddl::DEFAULT_SCHEMA;

/// Errors returned while introspecting a PostgreSQL database schema.
#[derive(Debug, Error)]
#[non_exhaustive]
pub enum IntrospectError {
    /// One of the requested schemas does not exist in `pg_catalog.pg_namespace`.
    #[error("schema `{schema}` does not exist")]
    UnknownSchema {
        /// Name of the missing schema.
        schema: String,
    },

    /// A database catalog query failed.
    #[error("database introspection failed: {0}")]
    Database(#[from] sqlx::Error),
}

/// Options controlling [`tables_with_options`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct IntrospectOptions {
    /// Auditstream history schema name to exclude from user-table introspection
    /// (defaults to [`DEFAULT_SCHEMA`], `"auditstream"`).
    pub audit_schema: String,
}

impl Default for IntrospectOptions {
    fn default() -> Self {
        Self {
            audit_schema: DEFAULT_SCHEMA.to_owned(),
        }
    }
}

impl IntrospectOptions {
    /// Creates [`IntrospectOptions`] skipping a custom audit schema name.
    #[must_use]
    pub fn with_audit_schema(audit_schema: impl Into<String>) -> Self {
        Self {
            audit_schema: audit_schema.into(),
        }
    }
}

/// Kind of capturable PostgreSQL table (`pg_class.relkind`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TableKind {
    /// Ordinary heap table (`relkind = 'r'`).
    Ordinary,
    /// Partitioned parent table (`relkind = 'p'`).
    Partitioned,
}

/// Identity column generation strategy (`pg_attribute.attidentity`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IdentityKind {
    /// `GENERATED ALWAYS AS IDENTITY` (`attidentity = 'a'`).
    Always,
    /// `GENERATED BY DEFAULT AS IDENTITY` (`attidentity = 'd'`).
    ByDefault,
}

/// Generated column storage strategy (`pg_attribute.attgenerated`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GeneratedKind {
    /// `GENERATED ALWAYS AS (...) STORED` (`attgenerated = 's'`).
    Stored,
    /// `GENERATED ALWAYS AS (...) VIRTUAL` (`attgenerated = 'v'`, PostgreSQL 18+).
    Virtual,
}

/// Metadata for a single non-dropped user column in `attnum` order.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ColumnInfo {
    /// Exact, unquoted column name.
    pub name: String,
    /// Formatted PostgreSQL data type from `pg_catalog.format_type(atttypid, atttypmod)`.
    pub data_type: String,
    /// Whether the column allows `NULL` (`NOT attnotnull`).
    pub nullable: bool,
    /// Identity kind if the column is an identity column.
    pub identity: Option<IdentityKind>,
    /// Generated kind (`Stored` or `Virtual`) if the column is generated.
    pub generated: Option<GeneratedKind>,
}

/// Child partition (or sub-partition) attached to a [`TableKind::Partitioned`] table.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PartitionInfo {
    /// PostgreSQL catalog OID (`pg_class.oid`).
    pub oid: u32,
    /// Exact, unquoted schema name.
    pub schema: String,
    /// Exact, unquoted partition table name.
    pub name: String,
    /// Whether this partition is a leaf (`Ordinary`) or itself `Partitioned`.
    pub kind: TableKind,
    /// Nested sub-partitions sorted by `(schema, name)`.
    pub partitions: Vec<Self>,
}

/// Introspected metadata for a capturable top-level user table.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TableInfo {
    /// PostgreSQL catalog OID (`pg_class.oid`).
    pub oid: u32,
    /// Exact, unquoted schema name.
    pub schema: String,
    /// Exact, unquoted table name.
    pub name: String,
    /// Ordinary or partitioned table kind.
    pub kind: TableKind,
    /// Non-dropped user columns in `attnum` ascending order.
    pub columns: Vec<ColumnInfo>,
    /// Primary key column names in key declaration order (empty if no primary key).
    pub primary_key: Vec<String>,
    /// Child partitions (and sub-partitions) for partitioned tables, empty for ordinary tables.
    pub partitions: Vec<PartitionInfo>,
}

/// Lists all non-system user schema names in deterministic alphabetical order, excluding
/// `options.audit_schema`, `pg_catalog`, `information_schema`, `pg_toast*`, and `pg_temp_*`.
///
/// # Errors
///
/// Returns [`IntrospectError::Database`] if the catalog query fails.
pub async fn user_schemas(
    pool: &PgPool,
    options: &IntrospectOptions,
) -> Result<Vec<String>, IntrospectError> {
    let mut schemas: Vec<String> = sqlx::query_scalar(
        "SELECT n.nspname \
           FROM pg_catalog.pg_namespace n \
          WHERE n.nspname <> $1 \
            AND n.nspname <> 'pg_catalog' \
            AND n.nspname <> 'information_schema' \
            AND n.nspname NOT LIKE 'pg_toast%' \
            AND n.nspname NOT LIKE 'pg_temp_%' \
          ORDER BY n.nspname ASC",
    )
    .bind(&options.audit_schema)
    .fetch_all(pool)
    .await?;

    schemas.sort();
    Ok(schemas)
}

/// Introspects ordinary and partitioned user tables across `schemas` using the default
/// `"auditstream"` audit schema exclusion.
///
/// Results are sorted deterministically by `(schema, name)`. Uses a fixed number of catalog
/// queries regardless of table count.
///
/// # Errors
///
/// - [`IntrospectError::UnknownSchema`] if any name in `schemas` does not exist.
/// - [`IntrospectError::Database`] if a PostgreSQL catalog query fails.
pub async fn tables(pool: &PgPool, schemas: &[&str]) -> Result<Vec<TableInfo>, IntrospectError> {
    tables_with_options(pool, schemas, &IntrospectOptions::default()).await
}

/// Introspects ordinary and partitioned user tables across `schemas` using `options`.
///
/// Skips views, materialized views, foreign tables, temporary tables, partitions as top-level
/// entries, the configured audit schema, system schemas (`pg_catalog`, `information_schema`,
/// `pg_toast*`, `pg_temp_*`), extension member tables (`pg_depend.deptype = 'e'`), and
/// migration metadata tables (`_prisma_migrations`, `__drizzle_migrations`).
///
/// # Errors
///
/// - [`IntrospectError::UnknownSchema`] if any name in `schemas` does not exist.
/// - [`IntrospectError::Database`] if a PostgreSQL catalog query fails.
pub async fn tables_with_options(
    pool: &PgPool,
    schemas: &[&str],
    options: &IntrospectOptions,
) -> Result<Vec<TableInfo>, IntrospectError> {
    if schemas.is_empty() {
        return Ok(Vec::new());
    }

    let requested: Vec<String> = schemas.iter().map(|s| (*s).to_owned()).collect();
    validate_schemas(pool, schemas, &requested).await?;

    let table_rows = fetch_table_rows(pool, &requested, &options.audit_schema).await?;
    if table_rows.is_empty() {
        return Ok(Vec::new());
    }

    let table_oids: Vec<i64> = table_rows.iter().map(|r| r.oid).collect();
    let partitioned_oids: Vec<i64> = table_rows
        .iter()
        .filter(|r| r.relkind == "p")
        .map(|r| r.oid)
        .collect();

    let column_rows = fetch_column_rows(pool, &table_oids).await?;
    let pk_rows = fetch_pk_rows(pool, &table_oids).await?;
    let partition_rows = fetch_partition_rows(pool, &partitioned_oids).await?;

    Ok(assemble_tables(
        table_rows,
        column_rows,
        pk_rows,
        partition_rows,
    ))
}

async fn validate_schemas(
    pool: &PgPool,
    schemas: &[&str],
    requested: &[String],
) -> Result<(), IntrospectError> {
    let existing: Vec<String> = sqlx::query_scalar(
        "SELECT nspname \
           FROM pg_catalog.pg_namespace \
          WHERE nspname = ANY($1)",
    )
    .bind(requested)
    .fetch_all(pool)
    .await?;

    let existing_set: HashSet<&str> = existing.iter().map(String::as_str).collect();
    for schema in schemas {
        if !existing_set.contains(*schema) {
            return Err(IntrospectError::UnknownSchema {
                schema: (*schema).to_owned(),
            });
        }
    }
    Ok(())
}

async fn fetch_table_rows(
    pool: &PgPool,
    requested: &[String],
    audit_schema: &str,
) -> Result<Vec<TableRow>, sqlx::Error> {
    sqlx::query_as(
        "SELECT \
           c.oid::bigint AS oid, \
           n.nspname AS schema_name, \
           c.relname AS table_name, \
           c.relkind::text AS relkind \
         FROM pg_catalog.pg_class c \
         JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace \
         WHERE n.nspname = ANY($1) \
           AND n.nspname <> $2 \
           AND n.nspname <> 'pg_catalog' \
           AND n.nspname <> 'information_schema' \
           AND n.nspname NOT LIKE 'pg_toast%' \
           AND n.nspname NOT LIKE 'pg_temp_%' \
           AND c.relkind IN ('r', 'p') \
           AND c.relpersistence <> 't' \
           AND NOT c.relispartition \
           AND c.relname NOT IN ('_prisma_migrations', '__drizzle_migrations') \
           AND NOT EXISTS ( \
             SELECT 1 \
               FROM pg_catalog.pg_depend d \
              WHERE d.classid = 'pg_catalog.pg_class'::regclass \
                AND d.objid = c.oid \
                AND d.deptype = 'e' \
           ) \
         ORDER BY n.nspname ASC, c.relname ASC",
    )
    .bind(requested)
    .bind(audit_schema)
    .fetch_all(pool)
    .await
}

async fn fetch_column_rows(
    pool: &PgPool,
    table_oids: &[i64],
) -> Result<Vec<ColumnRow>, sqlx::Error> {
    sqlx::query_as(
        "SELECT \
           a.attrelid::bigint AS table_oid, \
           a.attname AS column_name, \
           pg_catalog.format_type(a.atttypid, a.atttypmod) AS data_type, \
           NOT a.attnotnull AS nullable, \
           a.attidentity::text AS identity_kind, \
           a.attgenerated::text AS generated_kind \
         FROM pg_catalog.pg_attribute a \
         WHERE a.attrelid = ANY(ARRAY(SELECT x::oid FROM pg_catalog.unnest($1::bigint[]) AS x)) \
           AND a.attnum > 0 \
           AND NOT a.attisdropped \
         ORDER BY a.attrelid ASC, a.attnum ASC",
    )
    .bind(table_oids)
    .fetch_all(pool)
    .await
}

async fn fetch_pk_rows(pool: &PgPool, table_oids: &[i64]) -> Result<Vec<PkRow>, sqlx::Error> {
    sqlx::query_as(
        "SELECT \
           con.conrelid::bigint AS table_oid, \
           a.attname AS column_name \
         FROM pg_catalog.pg_constraint con \
         CROSS JOIN LATERAL pg_catalog.unnest(con.conkey) WITH ORDINALITY AS u(attnum, ord) \
         JOIN pg_catalog.pg_attribute a \
           ON a.attrelid = con.conrelid AND a.attnum = u.attnum \
         WHERE con.conrelid = ANY(ARRAY(SELECT x::oid FROM pg_catalog.unnest($1::bigint[]) AS x)) \
           AND con.contype = 'p' \
         ORDER BY con.conrelid ASC, u.ord ASC",
    )
    .bind(table_oids)
    .fetch_all(pool)
    .await
}

async fn fetch_partition_rows(
    pool: &PgPool,
    partitioned_oids: &[i64],
) -> Result<Vec<PartitionRow>, sqlx::Error> {
    if partitioned_oids.is_empty() {
        return Ok(Vec::new());
    }
    sqlx::query_as(
        "WITH RECURSIVE part_tree(parent_oid, child_oid) AS ( \
           SELECT i.inhparent, i.inhrelid \
             FROM pg_catalog.pg_inherits i \
            WHERE i.inhparent = ANY(ARRAY(SELECT x::oid FROM pg_catalog.unnest($1::bigint[]) AS x)) \
           UNION ALL \
           SELECT i.inhparent, i.inhrelid \
             FROM part_tree pt \
             JOIN pg_catalog.pg_inherits i ON i.inhparent = pt.child_oid \
         ) \
         SELECT \
           pt.parent_oid::bigint AS parent_oid, \
           c.oid::bigint AS child_oid, \
           n.nspname AS schema_name, \
           c.relname AS table_name, \
           c.relkind::text AS relkind \
         FROM part_tree pt \
         JOIN pg_catalog.pg_class c ON c.oid = pt.child_oid \
         JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace \
         WHERE c.relispartition \
         ORDER BY n.nspname ASC, c.relname ASC",
    )
    .bind(partitioned_oids)
    .fetch_all(pool)
    .await
}

fn assemble_tables(
    table_rows: Vec<TableRow>,
    column_rows: Vec<ColumnRow>,
    pk_rows: Vec<PkRow>,
    partition_rows: Vec<PartitionRow>,
) -> Vec<TableInfo> {
    let mut columns_by_oid: HashMap<i64, Vec<ColumnInfo>> = HashMap::new();
    for row in column_rows {
        let col = ColumnInfo {
            name: row.column_name,
            data_type: row.data_type,
            nullable: row.nullable,
            identity: parse_identity_kind(&row.identity_kind),
            generated: parse_generated_kind(&row.generated_kind),
        };
        columns_by_oid.entry(row.table_oid).or_default().push(col);
    }

    let mut pks_by_oid: HashMap<i64, Vec<String>> = HashMap::new();
    for row in pk_rows {
        pks_by_oid
            .entry(row.table_oid)
            .or_default()
            .push(row.column_name);
    }

    let mut children_by_parent: HashMap<i64, Vec<PartitionRow>> = HashMap::new();
    for row in partition_rows {
        children_by_parent
            .entry(row.parent_oid)
            .or_default()
            .push(row);
    }

    let mut result = Vec::with_capacity(table_rows.len());
    for row in table_rows {
        let oid_u32 = u32::try_from(row.oid).unwrap_or(0);
        let kind = parse_table_kind(&row.relkind);
        let columns = columns_by_oid.remove(&row.oid).unwrap_or_default();
        let primary_key = pks_by_oid.remove(&row.oid).unwrap_or_default();
        let partitions = if kind == TableKind::Partitioned {
            build_partition_tree(row.oid, &children_by_parent)
        } else {
            Vec::new()
        };

        result.push(TableInfo {
            oid: oid_u32,
            schema: row.schema_name,
            name: row.table_name,
            kind,
            columns,
            primary_key,
            partitions,
        });
    }

    // Locale-independent deterministic UTF-8 sort by (schema, name).
    result.sort_by(|a, b| a.schema.cmp(&b.schema).then_with(|| a.name.cmp(&b.name)));
    result
}

fn build_partition_tree(
    parent_oid: i64,
    children_by_parent: &HashMap<i64, Vec<PartitionRow>>,
) -> Vec<PartitionInfo> {
    let Some(children) = children_by_parent.get(&parent_oid) else {
        return Vec::new();
    };

    let mut list: Vec<PartitionInfo> = children
        .iter()
        .map(|row| {
            let kind = parse_table_kind(&row.relkind);
            let sub = if kind == TableKind::Partitioned {
                build_partition_tree(row.child_oid, children_by_parent)
            } else {
                Vec::new()
            };
            PartitionInfo {
                oid: u32::try_from(row.child_oid).unwrap_or(0),
                schema: row.schema_name.clone(),
                name: row.table_name.clone(),
                kind,
                partitions: sub,
            }
        })
        .collect();

    list.sort_by(|a, b| a.schema.cmp(&b.schema).then_with(|| a.name.cmp(&b.name)));
    list
}

fn parse_table_kind(relkind: &str) -> TableKind {
    if relkind == "p" {
        TableKind::Partitioned
    } else {
        TableKind::Ordinary
    }
}

fn parse_identity_kind(raw: &str) -> Option<IdentityKind> {
    match raw {
        "a" => Some(IdentityKind::Always),
        "d" => Some(IdentityKind::ByDefault),
        _ => None,
    }
}

fn parse_generated_kind(raw: &str) -> Option<GeneratedKind> {
    match raw {
        "s" => Some(GeneratedKind::Stored),
        "v" => Some(GeneratedKind::Virtual),
        _ => None,
    }
}

#[derive(Debug, FromRow)]
struct TableRow {
    oid: i64,
    schema_name: String,
    table_name: String,
    relkind: String,
}

#[derive(Debug, FromRow)]
struct ColumnRow {
    table_oid: i64,
    column_name: String,
    data_type: String,
    nullable: bool,
    identity_kind: String,
    generated_kind: String,
}

#[derive(Debug, FromRow)]
struct PkRow {
    table_oid: i64,
    column_name: String,
}

#[derive(Debug, FromRow)]
struct PartitionRow {
    parent_oid: i64,
    child_oid: i64,
    schema_name: String,
    table_name: String,
    relkind: String,
}
